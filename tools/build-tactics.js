#!/usr/bin/env node
/* Checks the puzzles of tools/tactics-source.js with the built-in engine and writes src/data/tactics.js.
 *
 * For each puzzle, the engine plays both sides from the key move on, and the line is rejected when
 * another move is about as good as the expected one (the puzzle would be ambiguous), except on the
 * last move where equally good moves are accepted as alternatives (e.g. another mate).
 * The built-in engine is weak (about 1500): read the report, and prefer a check with a real engine.
 *
 *   node tools/build-tactics.js     (takes a minute or two)
 */
const fs = require('fs');
const path = require('path');
const Chess = require('../src/chess/core.js')();
const SOURCE = require('./tactics-source.js');

const UNIQUE_GAP = 130;   // centipawns the expected move must beat the others by
const FINAL_SLACK = 40;   // last move: within this of the best move is fine

function check(p) {
  if (p.line) { // checked by hand: just make sure it is legal
    const pos = Chess.create(p.fen);
    for (const san of p.line) { const m = pos.fromSan(san); if (!m) throw new Error(p.id + ': illegal ' + san); pos.make(m); }
    return { line: p.line, alt: [], ok: true, notes: 'checked by hand' };
  }
  const pos = Chess.create(p.fen), line = [], notes = [];
  let ok = true, alt = [];
  for (let k = 0; k < p.moves; k++) {
    const lines = pos.think({ multipv: 4, depth: 7, movetime: 4000 });
    const want = k === 0 ? pos.fromSan(p.first) : pos.fromUci(lines[0].uci);
    if (!want) { ok = false; notes.push('illegal ' + p.first); break; }
    const wantUci = Chess.uci(want), mine = lines.find(x => x.uci === wantUci) || { cp: -99999, mate: null };
    const others = lines.filter(x => x.uci !== wantUci);
    const gap = others.length ? mine.cp - Math.max(...others.map(x => x.cp)) : Infinity;
    const mates = mine.mate && mine.mate > 0;
    notes.push(pos.san(want) + ' cp=' + mine.cp + (mine.mate ? ' M' + mine.mate : '') + ' gap=' + gap);
    if (k === p.moves - 1) {
      if (mates && mine.mate === 1) alt = others.filter(x => x.mate === 1).map(x => pos.san(pos.fromUci(x.uci)));
      if (mine.cp < lines[0].cp - FINAL_SLACK) { ok = false; notes.push('NOT THE BEST FINAL MOVE'); }
    } else if (!(gap >= UNIQUE_GAP || (mates && !others.some(x => x.mate > 0)))) {
      ok = false; notes.push('AMBIGUOUS');
    }
    line.push(pos.san(want));
    pos.make(want);
    if (k < p.moves - 1) { // the opponent's best defence
      const reply = pos.think({ multipv: 1, depth: 6, movetime: 2500 });
      if (!reply.length) { ok = false; notes.push('game over too early'); break; }
      const m = pos.fromUci(reply[0].uci);
      line.push(pos.san(m));
      pos.make(m);
    }
  }
  return { line, alt, ok, notes: notes.join(' ; ') };
}

/* same puzzle for the other colour: board turned half a turn, colours swapped */
function mirrorFen(fen) {
  const [placement, turn] = fen.split(' ');
  const rows = placement.split('/').reverse().map(row => {
    const cells = row.replace(/\d/g, d => '.'.repeat(+d));
    const swapped = [...cells].reverse().map(c => c === '.' ? c : c === c.toUpperCase() ? c.toLowerCase() : c.toUpperCase()).join('');
    return swapped.replace(/\.+/g, run => run.length);
  });
  return rows.join('/') + ' ' + (turn === 'w' ? 'b' : 'w') + ' - - 0 1';
}
function mirrorLine(fen, line) {
  const flip = sq => 'hgfedcba'['abcdefgh'.indexOf(sq[0])] + (9 - sq[1]);
  const a = Chess.create(fen), b = Chess.create(mirrorFen(fen)), out = [];
  for (const san of line) {
    const m = a.fromSan(san), u = Chess.uci(m), m2 = b.fromUci(flip(u.slice(0, 2)) + flip(u.slice(2, 4)) + u.slice(4));
    if (!m2) throw new Error('cannot mirror ' + san);
    out.push(b.san(m2));
    a.make(m); b.make(m2);
  }
  return out;
}

const all = [];
let failed = 0;
for (const p of SOURCE.puzzles) {
  const r = check(p);
  console.log((r.ok ? 'OK   ' : 'FAIL ') + p.id + ' | ' + r.line.join(' ') + (r.alt.length ? ' (also: ' + r.alt.join(', ') + ')' : '') + ' | ' + r.notes);
  if (!r.ok) failed++;
  all.push({ id: p.id, theme: p.theme, fen: p.fen, line: r.line, alt: r.alt });
}
if (failed) { console.error(failed + ' puzzle(s) rejected, src/data/tactics.js not written.'); process.exit(1); }
for (const id of SOURCE.mirrored) {
  const p = all.find(x => x.id === id);
  all.push({ id: id + '-n', theme: p.theme, fen: mirrorFen(p.fen), line: mirrorLine(p.fen, p.line), alt: [] });
}
const ordered = SOURCE.order.map(id => { const p = all.find(x => x.id === id); if (!p) throw new Error('unknown id in order: ' + id); return p; });
const unused = all.filter(p => !SOURCE.order.includes(p.id));
if (unused.length) console.warn('Not in order, left out: ' + unused.map(p => p.id).join(', '));

const q = JSON.stringify;
fs.writeFileSync(path.join(__dirname, '../src/data/tactics.js'),
  '/* Puzzles, generated by tools/build-tactics.js from tools/tactics-source.js: edit those, not this file.\n' +
  '   line: the solution in English SAN, player and opponent alternating. alt: other final moves that also count. */\n' +
  'const TACTICS = [\n' + ordered.map(p => '  { id: ' + q(p.id) + ', theme: ' + q(p.theme) + ', fen: ' + q(p.fen) + ',\n    line: [' + p.line.map(q).join(', ') + '], alt: [' + p.alt.map(q).join(', ') + '] }').join(',\n') +
  '\n];\n\nif (typeof module !== \'undefined\') module.exports = TACTICS;\n');
console.log('Wrote src/data/tactics.js (' + ordered.length + ' puzzles)');
